// Generates i18n.ts for the push function from the app's locale files, so
// push texts read exactly like the popups in the app.
// Run from the project root: node supabase/functions/push/build-i18n.mjs
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';

const KEYS = [
  '{name} in #{channel} ({server})',
  '{name} in {group}',
  'Mentioned you',
  'Sent you a message',
  'Calling you …',
  'New message',
  'Image',
  'Video',
  'Audio',
  'Voice message',
  'File',
  'Spoiler',
  'Code',
  'unknown',
  'channel',
];
const PLURAL = { key: '+{count} more messages', one: '+{count} more message' };
const LANGS = ['de', 'es', 'fr', 'it', 'pt-BR', 'nl', 'pl', 'tr', 'ru', 'uk', 'ar', 'ja', 'ko', 'zh-CN'];

const out = { en: { ...Object.fromEntries(KEYS.map((k) => [k, k])), [PLURAL.key]: { one: PLURAL.one, other: PLURAL.key } } };
for (const lang of LANGS) {
  const { default: dict } = await import(pathToFileURL(`src/i18n/locales/${lang}.ts`).href);
  out[lang] = {};
  for (const k of [...KEYS, PLURAL.key]) if (dict[k] !== undefined) out[lang][k] = dict[k];
}

const body = `/* Generated by build-i18n.mjs from src/i18n/locales – do not edit by hand. */
export type Plural = Partial<Record<Intl.LDMLPluralRule, string>>;

export const STRINGS: Record<string, Record<string, string | Plural>> = ${JSON.stringify(out, null, 2)};
`;
fs.writeFileSync(new URL('./i18n.ts', import.meta.url), body);
console.log('i18n.ts', Object.keys(out).length, 'languages');
